"""Pinned Pandoc OMML equation output for T103 math in DOCX and PPTX."""

from __future__ import annotations

import hashlib
import io
import json
import os
import zipfile
from pathlib import Path, PurePosixPath
from xml.etree import ElementTree

import pytest

from markweave.conversion.archive import ApprovedDocument
from markweave.conversion.pandoc import PandocConfig, PandocDocxConverter
from markweave.conversion.service import DocxConversionService
from markweave.presentations.models import PresentationOptions
from markweave.presentations.pandoc import PandocPptxConverter
from markweave.presentations.preparation import plan_presentation
from tests.golden.corpus import CorpusManifest
from tests.golden.omml import (
    GOLDEN_DOCX_LIMITS,
    MATH_NAMESPACE,
    PANDOC_VERSION,
    OmmlEquation,
    golden_equations,
    omml_equations,
)
from tests.golden.openxml import inspect_docx

pytestmark = [pytest.mark.integration, pytest.mark.requires_pandoc]
OMML_GOLDEN = Path("tests/corpus/math/golden/omml.json")
DRAWING = "http://schemas.openxmlformats.org/drawingml/2006/main"
DRAWING_2010 = "http://schemas.microsoft.com/office/drawing/2010/main"
MARKUP_COMPATIBILITY = "http://schemas.openxmlformats.org/markup-compatibility/2006"


def _source(manifest: CorpusManifest, case_id: str) -> bytes:
    return (manifest.root / manifest.by_id(case_id).entrypoint).read_bytes()


def _docx(tmp_path: Path, markdown: bytes) -> bytes:
    service = DocxConversionService(
        PandocDocxConverter(PandocConfig("pandoc", 30.0, 2.0, tmp_path), os.environ)
    )
    return service.convert(markdown.decode("utf-8"), None)


def _pptx(tmp_path: Path, markdown: bytes) -> bytes:
    plan = plan_presentation(
        ApprovedDocument(markdown.decode("utf-8"), PurePosixPath("document.md"), ()),
        PresentationOptions(),
    )
    converter = PandocPptxConverter(
        PandocConfig("pandoc", 30.0, 2.0, tmp_path),
        os.environ,
        slide_level=0 if plan.explicit_breaks else plan.options.slide_level,
    )
    return DocxConversionService(converter).convert_document(plan.document, None)


def _slide_parts(archive: zipfile.ZipFile) -> list[str]:
    slides = [
        name
        for name in archive.namelist()
        if name.startswith("ppt/slides/slide") and name.endswith(".xml")
    ]
    return sorted(
        slides, key=lambda name: int(name.removeprefix("ppt/slides/slide")[:-4])
    )


def _pptx_equations(data: bytes) -> tuple[OmmlEquation, ...]:
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        return tuple(
            equation
            for part in _slide_parts(archive)
            for equation in omml_equations(archive.read(part), part)
        )


def _pptx_text(data: bytes) -> str:
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        return "".join(
            node.text or ""
            for part in _slide_parts(archive)
            for node in ElementTree.fromstring(  # noqa: S314 - generated by pinned Pandoc
                archive.read(part)
            ).iter(f"{{{DRAWING}}}t")
        )


def _counts(equations: tuple[OmmlEquation, ...]) -> tuple[int, int]:
    return (
        sum(not equation.display for equation in equations),
        sum(equation.display for equation in equations),
    )


def _golden(markdown: bytes) -> tuple[OmmlEquation, ...]:
    golden = json.loads(OMML_GOLDEN.read_text(encoding="utf-8"))
    assert golden["schema_version"] == 1
    assert golden["pandoc_version"] == PANDOC_VERSION
    assert golden["source_markdown_sha256"] == hashlib.sha256(markdown).hexdigest()
    return golden_equations(golden)


def test_docx_renders_inline_and_display_math_as_native_omml(
    corpus_manifest: CorpusManifest, tmp_path: Path
) -> None:
    case = corpus_manifest.by_id("math-equations")
    markdown = _source(corpus_manifest, "math-equations")
    snapshot = inspect_docx(_docx(tmp_path, markdown), GOLDEN_DOCX_LIMITS)
    equations = omml_equations(
        snapshot.xml_parts["word/document.xml"], "word/document.xml"
    )

    assert equations == _golden(markdown)
    assert _counts(equations) == (
        case.expected["inline_equations"],
        case.expected["display_equations"],
    )
    text = " ".join(snapshot.document_text)
    literal_raw_tex = case.expected["literal_raw_tex"]
    assert isinstance(literal_raw_tex, list)
    for literal in literal_raw_tex:
        assert literal in text
        assert all(literal not in equation.text for equation in equations)
    assert "$" not in text
    assert list(tmp_path.iterdir()) == []


def test_docx_keeps_malformed_tex_as_literal_text_without_failing(
    corpus_manifest: CorpusManifest, tmp_path: Path
) -> None:
    case = corpus_manifest.by_id("math-malformed-tex")
    snapshot = inspect_docx(
        _docx(tmp_path, _source(corpus_manifest, "math-malformed-tex")),
        GOLDEN_DOCX_LIMITS,
    )
    equations = omml_equations(
        snapshot.xml_parts["word/document.xml"], "word/document.xml"
    )

    assert _counts(equations) == (
        case.expected["inline_equations"],
        case.expected["display_equations"],
    )
    assert [equation.text for equation in equations] == ["x2"]
    fallbacks = case.expected["literal_fallbacks"]
    assert isinstance(fallbacks, list)
    assert [text for text in snapshot.document_text if text in fallbacks] == fallbacks


def test_pptx_renders_the_same_native_omml_inside_drawingml_math(
    corpus_manifest: CorpusManifest, tmp_path: Path
) -> None:
    markdown = _source(corpus_manifest, "math-equations")
    result = _pptx(tmp_path, markdown)

    assert _pptx_equations(result) == _golden(markdown)
    with zipfile.ZipFile(io.BytesIO(result)) as archive:
        roots = [
            ElementTree.fromstring(archive.read(part))  # noqa: S314 - pinned Pandoc
            for part in _slide_parts(archive)
        ]
    wrappers = [node for root in roots for node in root.iter(f"{{{DRAWING_2010}}}m")]
    assert len(wrappers) == len(_golden(markdown))
    assert all(
        len(wrapper) == 1
        and wrapper[0].tag
        in {f"{{{MATH_NAMESPACE}}}oMath", f"{{{MATH_NAMESPACE}}}oMathPara"}
        for wrapper in wrappers
    )
    # Pandoc writes math shapes as an a14 choice without a fallback; documented limitation.
    alternates = [
        node
        for root in roots
        for node in root.iter(f"{{{MARKUP_COMPATIBILITY}}}AlternateContent")
    ]
    assert alternates
    for alternate in alternates:
        assert [child.tag for child in alternate] == [
            f"{{{MARKUP_COMPATIBILITY}}}Choice"
        ]
        assert alternate[0].attrib["Requires"] == "a14"
    assert "textbf{bold}" in _pptx_text(result)


def test_pptx_keeps_malformed_tex_as_literal_text_without_failing(
    corpus_manifest: CorpusManifest, tmp_path: Path
) -> None:
    case = corpus_manifest.by_id("math-malformed-tex")
    result = _pptx(tmp_path, _source(corpus_manifest, "math-malformed-tex"))
    equations = _pptx_equations(result)

    assert _counts(equations) == (
        case.expected["inline_equations"],
        case.expected["display_equations"],
    )
    assert [equation.text for equation in equations] == ["x2"]
    text = _pptx_text(result)
    fallbacks = case.expected["literal_fallbacks"]
    assert isinstance(fallbacks, list)
    for literal in fallbacks:
        assert literal in text
